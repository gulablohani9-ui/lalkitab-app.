class LalKitabEngine {
  static Map<String, dynamic> generateFullReport(Map<String, int> chart, int age) {
    List<Map<String, String>> fullReports = [];

    chart.forEach((planet, house) {
      String houseStr = house.toString();
      var planetData = LalKitabFullBookData[planet];

      if (planetData != null && planetData.containsKey(houseStr)) {
        var hData = planetData[houseStr]!;
        fullReports.add({
          "planet": planet,
          "house": houseStr,
          "shlok": hData["shlok"] ?? "",
          "swabhav": hData["swabhav"] ?? "",
          "vishesh_shartein": hData["vishesh_shartein"] ?? "",
          "upaay": hData["upaay"] ?? "",
          "savdhani": hData["savdhani"] ?? "",
        });
      } else {
        fullReports.add({
          "planet": planet,
          "house": houseStr,
          "shlok": "$planet खाना नम्बर $houseStr का लाल किताब श्लोक",
          "swabhav": "$planet खाना नं. $houseStr में लाल किताब के अनुसार जातक के जीवन पर विशिष्ट प्रभाव डालेगा।",
          "vishesh_shartein": "ग्रहों की युति, दृष्टि और पक्के घरों के समीकरण से विशेष फलित होगा।",
          "upaay": "संबंधित ग्रह की कारक वस्तुओं का दान व संबन्धित उपाय करें।",
          "savdhani": "निसर्ग के विपरीत कार्यों और वर्जित आचरण से बचें।",
        });
      }
    });

    return {"reports": fullReports};
  }

  static Map<String, int> calculateVarshphal(Map<String, int> birthChart, int age) {
    Map<String, int> vChart = {};
    birthChart.forEach((planet, house) {
      int newHouse = ((house - 1 + (age % 12)) % 12) + 1;
      vChart[planet] = newHouse;
    });
    return vChart;
  }
}
